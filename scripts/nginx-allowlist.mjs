// Renders the API allowlist of api/_proxy.js as nginx `map` blocks (deploy/nginx/api-allowlist.conf), so a
// same-origin nginx in front of the API answers the same routes and methods as the Vercel proxy.
//
//   node scripts/nginx-allowlist.mjs > deploy/nginx/api-allowlist.conf
//
// web/tests/nginx-allowlist.test.mjs fails when the checked-in file is not what this prints.
import { fileURLToPath } from 'node:url';

import { ROUTE_RULES, SCOPE_TARGET_PREFIX, allowedMethodsForProxyPath } from '../api/_proxy.js';

// Dynamic path segments: nginx matches the decoded URI, so the segment stays free of `?`, `#`, `%`, spaces.
const DYNAMIC_SEGMENT = '[A-Za-z0-9._~-]+';
const ITEM_SHAPE = /^[a-z0-9_/-]+(?:\[\^\/\]\+[a-z0-9_/-]*)*$/;

function rulePathItems(pattern) {
  // RegExp#source escapes `/` as `\/`.
  let body = pattern.source.replaceAll('\\/', '/').replace(/^\^/, '').replace(/\$$/, '');
  if (body.startsWith('(') && body.endsWith(')')) {
    body = body.slice(1, -1);
  }
  const items = body.split('|');
  for (const item of items) {
    if (!ITEM_SHAPE.test(item)) {
      throw new Error(`Route pattern ${pattern} is not renderable for nginx (item: ${item})`);
    }
  }
  return items;
}

const PLACEHOLDER = 'x';

// One entry per (scope, path item). The methods come from the proxy itself for a path that item matches, so
// a static item that a dynamic one also matches (`admin/yclients-credentials/test` vs `.../<id>`) gets the
// union, exactly as the proxy computes it. Items with the same scope and methods are folded into one
// alternation; static items go first because the maps take the first matching line.
function routeGroups() {
  const groups = new Map();
  for (const [scope, rules] of Object.entries(ROUTE_RULES)) {
    const items = new Set(rules.flatMap((rule) => rulePathItems(rule.pattern)));
    for (const item of items) {
      const dynamic = item.includes('[^/]+');
      const methods = allowedMethodsForProxyPath(scope, item.replaceAll('[^/]+', PLACEHOLDER));
      const key = `${scope}\n${dynamic}\n${methods.join(',')}`;
      if (!groups.has(key)) groups.set(key, { scope, dynamic, methods, items: [] });
      groups.get(key).items.push(item.replaceAll('[^/]+', DYNAMIC_SEGMENT));
    }
  }
  return [...groups.values()].sort((a, b) => Number(a.dynamic) - Number(b.dynamic));
}

const PREFIX = '(?:/api)?';

function scopeRegexBody(scope, items) {
  return `${PREFIX}/${scope}/(${items.join('|')})/*$`;
}

export function renderAllowlist() {
  const groups = routeGroups();
  const allowLines = [];
  const targetLines = [];
  for (const { scope, methods, items } of groups) {
    const body = scopeRegexBody(scope, items);
    allowLines.push(`    "~^${body}" "${methods.join(', ')}";`);
    targetLines.push(
      `    "~^(?:${methods.join('|')}) ${body}" "/${SCOPE_TARGET_PREFIX[scope]}$1";`,
    );
  }
  allowLines.push('    "~^/api/health/*$" "GET, HEAD";');
  targetLines.push('    "~^(?:GET|HEAD) /api/health/*$" "/health";');

  return `# Generated by scripts/nginx-allowlist.mjs from api/_proxy.js. Do not edit by hand.
# Included in the http {} context. $uri is the decoded, normalised request path (merge_slashes must be off).

# Methods the route answers, "" for a path that is not on the allowlist (404).
map $uri $api_allow {
    default "";
${allowLines.join('\n')}
}

# Upstream path for "METHOD uri", "" when the path is unknown or the method is not allowed (405 if $api_allow is set).
map "$request_method $uri" $api_target {
    default "";
${targetLines.join('\n')}
}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.stdout.write(renderAllowlist());
}
